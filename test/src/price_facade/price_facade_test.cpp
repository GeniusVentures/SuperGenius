TEST_F( PriceFacadeTest, HeldOffTierSkipsNetworkEntirely )
{
    stub_.OnPath( "/api/v3/simple/price", { 429, "text/html", "Too Many Requests" } );
    auto  client = NewClient();
    // Arm the hold-off via a first 429 fetch
    auto  first = client.FetchPrices( NewIoc(), { "genius-ai" }, "usd" );
    ASSERT_FALSE( first );

    // Now re-script the stub to serve good data — a held-off client must
    // still refuse to hit the network; the good script would produce SUCCESS
    // if any request leaked through.
    stub_.OnPath( "/api/v3/simple/price", { 200, "application/json", kGoodBody } );
    auto second = client.FetchPrices( NewIoc(), { "genius-ai" }, "usd" );
    ASSERT_FALSE( second );
    EXPECT_EQ( second.error().code, sgns::PriceFetchError::RateLimitExceeded );
    EXPECT_EQ( second.error().httpStatus, unsigned{ 429 } );
}

TEST_F( PriceFacadeTest, TimeoutRetriesToCapThree )
{
    stub_.OnPath( "/api/v3/simple/price",
                  { 200, "application/json", "{}", std::chrono::milliseconds( 3000 ) } );
    sgns::PriceHttpClient client( "http://127.0.0.1:" + std::to_string( stub_.Port() ),
                                  ZeroBackoffConfig(),
                                  std::chrono::seconds( 60 ),
                                  [] { return std::chrono::system_clock::now(); },
                                  std::chrono::milliseconds( 300 ) ); // short read timeout
    auto result = client.FetchPrices( NewIoc(), { "genius-ai" }, "usd" );
    ASSERT_FALSE( result );
    EXPECT_EQ( result.error().code, sgns::PriceFetchError::NetworkError );
    EXPECT_EQ( result.error().httpStatus, unsigned{ 0 } );
    EXPECT_EQ( client.AttemptsLastFetch(), 3 ); // cap, no fourth
}

