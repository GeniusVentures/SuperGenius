namespace
{
    sgns::RetryConfig ZeroBackoffConfig()
    {
        sgns::RetryConfig config;
        config.backoffBeforeRetry = { std::chrono::milliseconds( 0 ),
                                      std::chrono::milliseconds( 0 ),
                                      std::chrono::milliseconds( 0 ) };
        return config;
    }

    const char *kGoodBody = R"({"genius-ai":{"usd":0.19},"bitcoin":{"usd":61234.12}})";
    const char *kCloudFront403 =
        "<!DOCTYPE html><html><body><h1>403 ERROR</h1><p>ERROR: The request could not be "
        "satisfied</p><p>Generated by cloudfront (CloudFront)</p></body></html>";
} // namespace

class PriceFacadeTest : public ::testing::Test
{
protected:
    static void SetUpTestSuite() {}
    static void TearDownTestSuite() {}

    void SetUp() override
    {
        stub_.Start();
    }

    void TearDown() override
    {
        stub_.Shutdown();
    }

    sgns::testutil::HttpStubServer stub_;

    std::shared_ptr<boost::asio::io_context> NewIoc()
    {
        return std::make_shared<boost::asio::io_context>();
    }

    sgns::PriceHttpClient NewClient( sgns::RetryConfig config = ZeroBackoffConfig() )
    {
        return sgns::PriceHttpClient( "http://127.0.0.1:" + std::to_string( stub_.Port() ), config );
    }
};

TEST_F( PriceFacadeTest, Ok200ProducesQuotesWithD14Fields )
{
    stub_.OnPath( "/api/v3/simple/price", { 200, "application/json", kGoodBody } );
    auto  client = NewClient();
    auto  result = client.FetchPrices( NewIoc(), { "genius-ai", "bitcoin" }, "usd" );
    ASSERT_TRUE( result );
    const auto &quotes = result.value();
    ASSERT_EQ( quotes.size(), size_t{ 2 } );
    EXPECT_EQ( quotes[0].asset, "genius-ai" );
    EXPECT_EQ( quotes[0].currency, "usd" );
    EXPECT_DOUBLE_EQ( quotes[0].price, 0.19 );
    EXPECT_EQ( quotes[0].source, sgns::PriceSource::CoinGecko );
    EXPECT_FALSE( quotes[0].stale );
    const auto age = std::chrono::system_clock::now() - quotes[0].timestamp;
    EXPECT_LT( age, std::chrono::seconds( 5 ) ); // D-14: fetch time ~ now
    EXPECT_DOUBLE_EQ( quotes[1].price, 61234.12 );
    EXPECT_EQ( client.AttemptsLastFetch(), 1 );
}

TEST_F( PriceFacadeTest, Blocked403FailsImmediatelyWithStatus )
{
    stub_.OnPath( "/api/v3/simple/price", { 403, "text/html", kCloudFront403 } );
    auto  client = NewClient();
    auto  result = client.FetchPrices( NewIoc(), { "genius-ai" }, "usd" );
    ASSERT_FALSE( result );
    EXPECT_EQ( result.error().code, sgns::PriceFetchError::Blocked );
    EXPECT_EQ( result.error().httpStatus, unsigned{ 403 } );
    EXPECT_NE( result.error().Message().find( "403" ), std::string::npos );
    EXPECT_NE( result.error().Message().find( "blocked" ), std::string::npos );
    EXPECT_EQ( client.AttemptsLastFetch(), 1 ); // never retried
}

