// ---- Policy unit cases (Task 2 behaviors, hermetic) ----

TEST( PriceRetryPolicyTest, IsTransientTruthTable )
{
    using E = sgns::PriceFetchError;
    using C = sgns::http::ClientError;
    const std::vector<std::pair<sgns::PriceFetchFailure, bool>> cases = {
        // D-14: {NetworkError, 0} rows carry transport classifications —
        // strict gating delegates to IsTransientTransport.
        { { E::NetworkError, 0, C::TIMEOUT }, true },
        { { E::NetworkError, 0, C::CONNECT_FAILED }, true },
        { { E::NetworkError, 0, C::RESOLVE_FAILED }, true },
        // Permanent transport classes are never transient (D-14 core claim).
        { { E::NetworkError, 0, C::TLS_HANDSHAKE_FAILED }, false },
        { { E::NetworkError, 0, C::TLS_CA_LOAD_FAILED }, false },
        { { E::NetworkError, 0, C::WRITE_FAILED }, false },
        { { E::NetworkError, 0, C::READ_INTERRUPTED }, false },
        // Unclassified {NetworkError, 0} is NOT transient (strict).
        { { E::NetworkError, 0 }, false },
        { { E::Blocked, 403 }, false },
        { { E::RateLimitExceeded, 429 }, false },
        { { E::HttpStatus, 404 }, false },
        { { E::HttpStatus, 500 }, false },
        { { E::HttpStatus, 502 }, false },
        { { E::JsonParseError, 200 }, false },
        { { E::EmptyInput, 0 }, false },
        { { E::NoDataFound, 200 }, false },
    };
    for ( const auto &[failure, expected] : cases )
    {
        EXPECT_EQ( sgns::IsTransient( failure ), expected ) << failure.Message();
    }
}

TEST( PriceRetryPolicyTest, ShouldRetryCapsAtThreeForTransient )
{
    sgns::RetryConfig config; // defaults: 3 attempts
    const sgns::PriceFetchFailure transient{ sgns::PriceFetchError::NetworkError, 0, sgns::http::ClientError::TIMEOUT };
    EXPECT_EQ( sgns::ShouldRetry( transient, 1, config ), sgns::RetryDecision::Retry );
    EXPECT_EQ( sgns::ShouldRetry( transient, 2, config ), sgns::RetryDecision::Retry );
    EXPECT_EQ( sgns::ShouldRetry( transient, 3, config ), sgns::RetryDecision::GiveUp ); // no 4th
}

TEST( PriceRetryPolicyTest, ShouldRetryNeverRetriesStatusBearing )
{
    sgns::RetryConfig config;
    const sgns::PriceFetchFailure blocked{ sgns::PriceFetchError::Blocked, 403 };
    const sgns::PriceFetchFailure limited{ sgns::PriceFetchError::RateLimitExceeded, 429 };
    EXPECT_EQ( sgns::ShouldRetry( blocked, 1, config ), sgns::RetryDecision::GiveUp );
    EXPECT_EQ( sgns::ShouldRetry( limited, 1, config ), sgns::RetryDecision::GiveUp );
}

TEST( PriceRetryPolicyTest, RateLimitHoldOffWithInjectableClock )
{
    auto       now = std::chrono::system_clock::time_point{} + std::chrono::hours( 1000 );
    auto       nowFn = [&now]() { return now; };
    sgns::RateLimitHoldOff holdOff( nowFn );

    EXPECT_FALSE( holdOff.IsHeldOff() ); // before any trigger
    holdOff.TriggerHoldOff( std::chrono::seconds( 60 ) );
    EXPECT_TRUE( holdOff.IsHeldOff() );
    now += std::chrono::seconds( 59 );
    EXPECT_TRUE( holdOff.IsHeldOff() );
    now += std::chrono::seconds( 2 ); // 61s total
    EXPECT_FALSE( holdOff.IsHeldOff() );

    // Re-triggerable: a second trigger re-arms from the new now
    holdOff.TriggerHoldOff( std::chrono::seconds( 60 ) );
    EXPECT_TRUE( holdOff.IsHeldOff() );
}

TEST( PriceFetchErrorTest, MessageEmbedsStatus )
{
    sgns::PriceFetchFailure blocked{ sgns::PriceFetchError::Blocked, 403 };
    EXPECT_NE( blocked.Message().find( "403" ), std::string::npos );
    EXPECT_NE( blocked.Message().find( "blocked" ), std::string::npos );

    sgns::PriceFetchFailure limited{ sgns::PriceFetchError::RateLimitExceeded, 429 };
    EXPECT_NE( limited.Message().find( "429" ), std::string::npos );

    sgns::PriceFetchFailure plain{ sgns::PriceFetchError::NetworkError, 0 };
    EXPECT_EQ( plain.Message(), "Network Error" );

    sgns::PriceFetchFailure def;
    EXPECT_EQ( def.httpStatus, unsigned{ 0 } );
}

